/* Generate self-contained ESM modules for the Edge runtime from canonical client rules. */
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');let stale=false;
for(const name of ['field-model','mission-rules','expedition-model','story-plan','trace-codec']){
 const source=fs.readFileSync(path.join(root,name+'.js'),'utf8');
 const output='// Generated by tools/build-server-models.cjs; edit the root model instead.\nconst module={exports:{}};\n'+source+'\nexport default module.exports;\n';
 const target=path.join(root,'server/rewards/models',name+'.mjs');
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){console.error('Stale server model: '+name);stale=true;}}
 else fs.writeFileSync(target,output);
}
if(stale)process.exitCode=1;
